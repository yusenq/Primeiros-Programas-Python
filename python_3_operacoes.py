num_1 = float(input('Insira um número de sua preferência: '))
num_2 = float(input('Insira outro número de sua preferência: '))

soma = num_1 + num_2
subtracao = num_1 - num_2
multiplicacao = num_1 * num_2
divisao = num_1 / num_2
resto_divisao = num_1 % num_2

print(f'A soma entre os números escolhidos é: {soma}!')
print(f'A subtração entre os números escolhidos é: {subtracao}!')
print(f'A multiplicação entre os números escolhidos é: {multiplicacao}!')
print(f'A divisão entre os números escolhidos é: {divisao}!')
print(f'O resto da divisão entre os números escolhidos é: {resto_divisao}')